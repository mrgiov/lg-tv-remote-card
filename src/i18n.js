export const DICTIONARIES = { en, it };

/** 'it' for Italian Home Assistant (hass.locale.language, then hass.language), English for everything else. */
export function languageOf(hass) {
  const language = String(hass?.locale?.language ?? hass?.language ?? '').toLowerCase();
  return language === 'it' || language.startsWith('it-') ? 'it' : 'en';
}

/** Returns t(key, vars): the text in `language`, else English, else the key itself. */
export function translator(language) {
  const dictionary = DICTIONARIES[language] ?? en;
  return (key, vars = {}) => (dictionary[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
